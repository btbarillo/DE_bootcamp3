
-- Patient Dimension
CREATE TABLE Dim_Patient (
    patient_key INT PRIMARY KEY,
    patient_id VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    age_group VARCHAR(20) CHECK (age_group IN ('0-17', '18-25', '26-40', '41-60', '60+')),
    gender VARCHAR(10),
    hmo_provider VARCHAR(50),
    membership_type VARCHAR(30) CHECK (membership_type IN ('Principal', 'Dependent', 'Senior', 'Self-Pay'))
);

-- Department Dimension
CREATE TABLE Dim_Department (
    department_key INT PRIMARY KEY,
    department_code VARCHAR(15) NOT NULL UNIQUE,
    department_name VARCHAR(100) NOT NULL,
    head_physician VARCHAR(100),
    building_wing VARCHAR(50)
);

-- Date Dimension
CREATE TABLE Dim_Date (
    date_key INT PRIMARY KEY, -- YYYYMMDD format (e.g., 20260105)
    full_date DATE NOT NULL,
    day_of_week VARCHAR(15),
    calendar_month INT CHECK (calendar_month BETWEEN 1 AND 12),
    month_name VARCHAR(15),
    calendar_quarter VARCHAR(5),
    calendar_year INT,
    is_holiday_ph BOOLEAN DEFAULT FALSE
);

-- ==========================================
-- 3. CREATE FACT TABLE
-- ==========================================

CREATE TABLE Fact_Patient_Visits (
    visit_db_id SERIAL PRIMARY KEY,
    visit_id VARCHAR(25) NOT NULL UNIQUE,
    patient_key INT REFERENCES Dim_Patient(patient_key),
    department_key INT REFERENCES Dim_Department(department_key),
    visit_date_key INT REFERENCES Dim_Date(date_key),
    consultation_fee NUMERIC(10, 2) DEFAULT 0.00,
    lab_test_fees NUMERIC(10, 2) DEFAULT 0.00,
    hmo_coverage_amount NUMERIC(10, 2),
    patient_copay_amount NUMERIC(10, 2) DEFAULT 0.00,
    wait_time_mins INT,
    consultation_length_mins INT,
    visit_status VARCHAR(30) CHECK (visit_status IN ('Completed', 'completed', 'Walkout / Cancelled', 'No-Show')),
    triage_priority VARCHAR(30)
);

